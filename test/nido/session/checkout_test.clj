(ns nido.session.checkout-test
  (:require
   [babashka.fs :as fs]
   [babashka.process :refer [shell]]
   [clojure.string :as str]
   [clojure.test :refer [deftest is testing]]
   [nido.platform.core :as core]
   [nido.session.checkout :as checkout]
   [nido.session.state :as state]))

(defn- sh [dir & args]
  (apply shell {:dir (str dir) :out :string :err :string} args))

(defn- with-two-workspaces
  "Run `f` with a colocated jj repo holding `f.txt` and `g.edn`, two workspaces `a` and `b` of it,
   and the nido home in the same temp dir; `f` gets the two workspace paths."
  [f]
  (let [tmp (fs/create-temp-dir)
        src (fs/path tmp "src")
        a   (str (fs/path tmp "a"))
        b   (str (fs/path tmp "b"))]
    (try
      (fs/create-dirs src)
      (sh src "jj" "git" "init" "--colocate")
      (spit (str (fs/path src "f.txt")) "base\n")
      (spit (str (fs/path src "g.edn")) "{}\n")
      (sh src "jj" "commit" "-m" "base")
      (sh src "jj" "workspace" "add" "--name" "a" a)
      (sh src "jj" "workspace" "add" "--name" "b" b)
      (with-redefs [core/nido-home (constantly (str tmp))]
        (f a b))
      (finally (fs/delete-tree tmp)))))

(deftest the-checkout-merges-every-members-working-copy
  (with-two-workspaces
    (fn [a b]
      (is (checkout/jj-workspace? a))
      (spit (str (fs/path a "a.clj")) "(ns a)\n")
      (spit (str (fs/path b "g.edn")) "{:b 1}\n")
      (let [setups (atom [])
            dir    (checkout/refresh! "p--ws" {a "a" b "b"} #(swap! setups conj %))]
        (is (= (checkout/checkout-dir "p--ws") dir))
        (is (fs/exists? (fs/path dir "a.clj")) "a's new source file")
        (is (= "{:b 1}\n" (slurp (str (fs/path dir "g.edn")))) "b's changed resource")
        (is (= [dir] @setups) "a new checkout is set up once")
        (testing "a later change, code or not, reaches it on the next refresh"
          (spit (str (fs/path b "t.html")) "<p/>")
          (checkout/refresh! "p--ws" {a "a" b "b"} #(swap! setups conj %))
          (is (fs/exists? (fs/path dir "t.html")))
          (is (= 1 (count @setups)) "and is not set up again"))
        (testing "a conflicting merge is refused, and the checkout keeps what it had"
          (spit (str (fs/path a "g.edn")) "{:a 1}\n")
          (let [e (try (checkout/refresh! "p--ws" {a "a" b "b"}) nil
                       (catch clojure.lang.ExceptionInfo e e))]
            (is (= :checkout-conflict (:reason (ex-data e))))
            (is (= ["g.edn"] (:paths (ex-data e)))))
          (is (= "{:b 1}\n" (slurp (str (fs/path dir "g.edn"))))))
        (testing "removing it forgets the workspace and deletes the directory"
          (checkout/remove! "p--ws" a)
          (is (not (fs/exists? dir)))
          (is (not (re-find #"nido-runtime" (:out (sh a "jj" "workspace" "list"))))))))))

(deftest a-checkout-whose-directory-was-deleted-is-created-again
  ;; Reclaiming an orphan state directory deletes the checkout without telling jj, which keeps the
  ;; workspace name; a refresh that only re-adds it is refused for as long as that name stands.
  (with-two-workspaces
    (fn [a _]
      (let [dir (checkout/refresh! "p--ws" {a "a"})]
        (fs/delete-tree (state/instance-state-dir "p--ws"))
        (spit (str (fs/path a "a.clj")) "(ns a)\n")
        (is (= dir (checkout/refresh! "p--ws" {a "a"})))
        (is (fs/exists? (fs/path dir "a.clj")) "it holds the members' working copies again")
        (is (= 1 (count (re-seq #"nido-runtime" (:out (sh a "jj" "workspace" "list")))))
            "under the one workspace")))))

(deftest two-runtimes-whose-ids-fold-alike-get-two-checkouts
  ;; `feat/x` is kept as `feat~x`, beside a runtime keyed `feat-x`: two state directories, so two
  ;; jj workspaces, though jj's spelling of either id folds `~` to `-`.
  (with-two-workspaces
    (fn [a _]
      (let [one (checkout/refresh! "p--feat~x" {a "a"})
            two (checkout/refresh! "p--feat-x" {a "a"})]
        (is (not= one two))
        (is (fs/exists? (fs/path one "f.txt")))
        (is (fs/exists? (fs/path two "f.txt")))))))

(deftest a-refresh-keeps-what-the-runtime-rendered-into-its-checkout
  ;; A config-file service writes the runtime's ports and database over a tracked file in the
  ;; checkout; the members' copies of that file carry none of them.
  (with-two-workspaces
    (fn [a b]
      (let [dir       (checkout/refresh! "p--ws" {a "a" b "b"})
            generated (str (fs/path dir "g.edn"))]
        (spit generated ";; AUTO-GENERATED by nido\n{:port 5000}\n")
        (state/write-session! "p--ws" {:service-defs   [{:type :config-file :name :cfg}
                                                        {:type :process :name :repl}]
                                       :service-states {:cfg {:path generated} :repl {:pid 1}}})
        (spit (str (fs/path a "a.clj")) "(ns a)\n")
        ;; Whoever refreshes — a sync, a join, the preflight of a restarting join — names no files.
        (checkout/refresh! "p--ws" {a "a" b "b"})
        (is (fs/exists? (fs/path dir "a.clj")) "the members' change still arrives")
        (is (= ";; AUTO-GENERATED by nido\n{:port 5000}\n" (slurp generated))
            "and the runtime's own config is what it was")))))

(deftest stacked-members-are-merged-with-every-unrecorded-edit
  ;; b's working copy sits on top of a's. Snapshotting a rewrites a's commit and rebases b's,
  ;; leaving b's workspace stale: b is snapshotted first, then brought up to date, and neither
  ;; member's edit is lost.
  (with-two-workspaces
    (fn [a b]
      (sh b "jj" "new" "a@")
      (spit (str (fs/path a "a.clj")) "(ns a)\n")
      (spit (str (fs/path b "b.clj")) "(ns b)\n")
      (let [dir (checkout/refresh! "p--ws" {a "a" b "b"})]
        (is (fs/exists? (fs/path dir "a.clj")) "a's edit reaches the checkout")
        (is (fs/exists? (fs/path dir "b.clj")) "and b's")
        (is (= "(ns b)\n" (slurp (str (fs/path b "b.clj")))) "b keeps its edit on disk")
        (is (fs/exists? (fs/path b "a.clj")) "b's workspace is brought up to date under a's")
        (is (zero? (:exit (shell {:dir b :out :string :err :string :continue true}
                                 "jj" "log" "-r" "@" "--no-graph" "-T" "commit_id"))))
            "and is not left stale"))))

(deftest a-member-another-workspace-left-stale-refuses-the-refresh
  ;; b sits on a. Rewriting a's commit from a rebases b's and leaves b's workspace stale, b's edit
  ;; only on its disk: the refresh is refused, naming b, rather than serving b without it.
  (with-two-workspaces
    (fn [a b]
      (sh b "jj" "new" "a@")
      (let [dir (checkout/refresh! "p--ws" {a "a" b "b"})]
        (spit (str (fs/path b "b.clj")) "(ns b)\n")
        (spit (str (fs/path a "a.clj")) "(ns a)\n")
        (sh a "jj" "describe" "-m" "a rewritten")
        (let [e (try (checkout/refresh! "p--ws" {a "a" b "b"}) nil
                     (catch clojure.lang.ExceptionInfo e e))]
          (is (= :checkout-unsnapshottable (:reason (ex-data e))))
          (is (= ["b"] (:members (ex-data e)))))
        (is (not (fs/exists? (fs/path dir "b.clj"))) "the checkout keeps what it had")
        (is (= "(ns b)\n" (slurp (str (fs/path b "b.clj")))) "and b's edit stays on its disk")))))

(deftest members-sharing-a-working-copy-commit-refuse-the-refresh
  (with-two-workspaces
    (fn [a b]
      (sh b "jj" "edit" "a@")
      (let [e (try (checkout/refresh! "p--ws" {a "a" b "b"}) nil
                   (catch clojure.lang.ExceptionInfo e e))]
        (is (= :checkout-unsnapshottable (:reason (ex-data e))))
        (is (= #{"a" "b"} (set (:members (ex-data e)))))))))

(deftest git-resolves-from-a-checkout-only-when-told-its-git-dir
  ;; The checkout lies outside every git repository, so a project that shells to git at startup
  ;; (brian stamps its build from `git log`) found none and its JVM died before nREPL started.
  (with-two-workspaces
    (fn [a _]
      (let [dir  (checkout/refresh! "p--ws" {a "a"})
            git  #(apply shell (cond-> {:dir dir :out :string :err :string :continue true}
                                 % (assoc :extra-env {"GIT_DIR" %}))
                         "git" "log" "-1" "--format=%s" [])]
        (is (not (zero? (:exit (git nil)))) "unaided, git finds no repository there")
        (is (= "base" (str/trim (:out (git (checkout/git-dir dir)))))
            "told the source's git dir, it reads the source's history")))))
